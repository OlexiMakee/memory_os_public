_GRPO_BODY = _HEADER + '''from trl import GRPOTrainer, GRPOConfig
from datasets import load_dataset
import json
import re
''' + _PEFT_SETUP + '''
# GRPO samples a group of rollouts per prompt at train time and ranks them
# against each other's reward -- there is no chosen/rejected pair up front.
# Expected dataset column: "prompt" only.
dataset = load_dataset("json", data_files="{dataset_path}", split="train")


def _completion_text(value) -> str:
    if isinstance(value, str):
        return value
    if isinstance(value, list):
        return "\\n".join(
            str(message.get("content", ""))
            for message in value
            if isinstance(message, dict)
        )
    return ""


def _available_actions(prompt) -> set:
    text = _completion_text(prompt)
    match = re.search(r"<available_actions>\\s*(.*?)\\s*</available_actions>", text, re.DOTALL)
    if not match:
        return set()
    names = set()
    for line in match.group(1).splitlines():
        name, separator, _description = line.partition(":")
        name = name.strip()
        if separator and re.fullmatch(r"[A-Za-z0-9_.-]+", name):
            names.add(name)
    return names


def reward_{func_name}(completions, prompts, **kwargs) -> list:
    rewards = []
    for index, completion in enumerate(completions):
        prompt = prompts[index] if index < len(prompts) else ""
        allowed = _available_actions(prompt)
        try:
            payload = json.loads(_completion_text(completion))
        except (TypeError, ValueError):
            rewards.append(0.0)
            continue
        valid = (
            isinstance(payload, dict)
            and set(payload) == {{"action", "args"}}
            and isinstance(payload.get("action"), str)
            and isinstance(payload.get("args"), dict)
            and payload["action"] in allowed
        )
        rewards.append(1.0 if valid else 0.0)
    return rewards


trainer = GRPOTrainer(
    model=model,
    tokenizer=tokenizer,
    train_dataset=dataset,
    reward_funcs=[reward_{func_name}],
    args=GRPOConfig(
        output_dir="{output_dir}",
        per_device_train_batch_size={batch_size},
        gradient_accumulation_steps={grad_accum},
        num_train_epochs={epochs},
        learning_rate={learning_rate},
        logging_steps=10,
        save_strategy="epoch",
    ),
)
''' + _SAVE_FOOTER

_METHOD_BODIES: Dict[str, str] = {
    "sft": _SFT_BODY,
    "dpo": _DPO_BODY,
    "grpo": _GRPO_BODY,
}


@dataclass
class LoraTrainingConfig:
    """
    Training hyperparameters for one skill adapter, mirroring Unsloth/TRL/PEFT
    arguments directly so render_script() has nothing to guess at runtime.
    Defaults are reasonable for an 8B model in 4-bit on an 8GB-VRAM card —
    not tuned for any particular dataset.

    method picks which trl trainer the rendered script uses:
      "sft"  — supervised fine-tuning on (prompt, completion) examples; the
               default, and the only stage needed for most action adapters.
      "dpo"  — preference optimization on (prompt, chosen, rejected) triples;
               a second stage after an "sft" pass, for ranking response
               quality rather than teaching output format.
      "grpo" — group-relative policy optimization with a reward function the
               rendered script computes by validating action JSON against the
               vocabulary embedded in each prompt.
    """

    name: str
    base_model: str
    dataset_path: str
    output_dir: str
    method: str = "sft"
    max_seq_length: int = 2048
    rank: int = 16
    alpha: int = 32
    dropout: float = 0.0
    target_modules: List[str] = field(
        default_factory=lambda: ["q_proj", "k_proj", "v_proj", "o_proj"]
    )
    batch_size: int = 2
    grad_accum: int = 4
    epochs: int = 3
    learning_rate: float = 2e-4

    def __post_init__(self) -> None:
        if self.method not in _METHOD_BODIES:
            raise ValueError(
                f"unknown method {self.method!r}, expected one of {sorted(_METHOD_BODIES)}"
            )

    def render_script(self) -> str:
        body = _METHOD_BODIES[self.method]
        func_name = re.sub(r"[^0-9a-zA-Z_]", "_", self.name) or "adapter"
        if func_name[0].isdigit():
            func_name = f"_{func_name}"
        return body.format(
            method=self.method,
            name=self.name,
            func_name=func_name,
            base_model=self.base_model,
            dataset_path=self.dataset_path,
            output_dir=self.output_dir,
            max_seq_length=self.max_seq_length,
            rank=self.rank,
            alpha=self.alpha,
            dropout=self.dropout,
            target_modules=self.target_modules,
            batch_size=self.batch_size,
            grad_accum=self.grad_accum,
            epochs=self.epochs,
            learning_rate=self.learning_rate,
        )

    def write_script(self, path: Path) -> None:
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(self.render_script(), encoding="utf-8")
