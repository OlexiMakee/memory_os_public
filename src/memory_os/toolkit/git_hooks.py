"""Git hooks and auto-snapshot integration toolkit.

Hooks resolve the ``memory_os`` CLI at *runtime* (active ``$VIRTUAL_ENV``, then common
project venv directories, then ``PATH``), so they keep working when a consumer project
uses a non-default venv name (e.g. ``venv_auto``).

The pre-commit gate depends on the repository role:

* **package** — the repo *is* memory_os (``pyproject.toml`` ``[project].name`` is
  ``memory_os``): runs the full ``release-check --target private``.
* **consumer** — any project that merely *uses* memory_os: runs ``validate`` +
  ``security scan``. ``release-check`` is not applicable there (it requires the
  memory_os ``pyproject.toml`` and the memory_os retrieval eval suite).
"""

from __future__ import annotations

from pathlib import Path
from typing import List, Tuple

from memory_os.core.toml_compat import load_toml_path

PACKAGE_NAMES = {"memory_os", "memory-os"}

# Searched in order; first executable memory_os wins. $VIRTUAL_ENV is checked first.
VENV_CANDIDATES = ("venv_auto", ".venv", "venv", "env")

_RESOLVE_CLI = """#!/bin/bash
# Generated by: memory_os integrate --install-git-hooks (role: {role})
cd "$(git rev-parse --show-toplevel)" || exit 1
MEMORY_OS_BIN=""
for venv in "${{VIRTUAL_ENV:-}}" {venvs}; do
    [ -n "$venv" ] || continue
    for candidate in "$venv/bin/memory_os" "$venv/Scripts/memory_os"; do
        if [ -x "$candidate" ]; then
            MEMORY_OS_BIN="$candidate"
            break 2
        fi
    done
done
if [ -z "$MEMORY_OS_BIN" ] && command -v memory_os >/dev/null 2>&1; then
    MEMORY_OS_BIN="$(command -v memory_os)"
fi
"""

_PRE_COMMIT_MISSING = """if [ -z "$MEMORY_OS_BIN" ]; then
    echo "memory_os pre-commit: CLI not found (checked \\$VIRTUAL_ENV, {venvs}, PATH)." >&2
    echo "Install memory_os into the project venv, or bypass once: git commit --no-verify" >&2
    exit 1
fi
"""

_PRE_COMMIT_GATES = {
    "package": '"$MEMORY_OS_BIN" release-check --target private || exit 1\n',
    "consumer": '"$MEMORY_OS_BIN" validate || exit 1\n"$MEMORY_OS_BIN" security scan || exit 1\n',
}

_POST_COMMIT_BODY = """if [ -z "$MEMORY_OS_BIN" ]; then
    echo "memory_os post-commit: CLI not found, commit snapshot skipped." >&2
    exit 0
fi
"$MEMORY_OS_BIN" memory write --type fact --summary "Git commit: $(git log -1 --pretty=format:'%h - %s')"
"""


def detect_repo_role(root: Path) -> str:
    """Return ``"package"`` if root is the memory_os source repo, else ``"consumer"``."""
    pyproject = root / "pyproject.toml"
    if not pyproject.is_file():
        return "consumer"
    try:
        data = load_toml_path(pyproject)
    except (OSError, ValueError):
        return "consumer"
    name = str(data.get("project", {}).get("name", "")).strip().lower()
    return "package" if name in PACKAGE_NAMES else "consumer"


def render_pre_commit_hook(role: str) -> str:
    if role not in _PRE_COMMIT_GATES:
        raise ValueError(f"unknown repo role: {role!r}")
    venvs = " ".join(VENV_CANDIDATES)
    return (
        _RESOLVE_CLI.format(role=role, venvs=venvs)
        + _PRE_COMMIT_MISSING.format(venvs=", ".join(VENV_CANDIDATES))
        + _PRE_COMMIT_GATES[role]
    )


def render_post_commit_hook(role: str) -> str:
    return _RESOLVE_CLI.format(role=role, venvs=" ".join(VENV_CANDIDATES)) + _POST_COMMIT_BODY


def install_git_hooks(root: Path) -> Tuple[bool, List[str]]:
    """Install pre-commit and post-commit Git hooks in root/.git/hooks.

    Returns (True, actions) if successful, or (False, actions) if root is not a git repository.
    """
    git_dir = root / ".git"
    if not git_dir.exists() or not git_dir.is_dir():
        return False, ["Git repository not found (no .git directory)."]

    hooks_dir = git_dir / "hooks"
    hooks_dir.mkdir(parents=True, exist_ok=True)

    role = detect_repo_role(root)
    actions: List[str] = []

    pre_commit_path = hooks_dir / "pre-commit"
    pre_commit_path.write_text(render_pre_commit_hook(role), encoding="utf-8")
    pre_commit_path.chmod(0o755)
    actions.append(f"installed {pre_commit_path} (role={role})")

    post_commit_path = hooks_dir / "post-commit"
    post_commit_path.write_text(render_post_commit_hook(role), encoding="utf-8")
    post_commit_path.chmod(0o755)
    actions.append(f"installed {post_commit_path} (role={role})")

    return True, actions
